#!/usr/bin/env python3
"""Generate LitRoot's offline formula engine from its paper-fetch owner."""

import argparse
import hashlib
from pathlib import Path

SOURCE = (
    Path(__file__).resolve().parents[1]
    / "src/paper_fetch/resources/formula/mathjax_engine.mjs"
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reader_root", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = args.reader_root / "src/shared/markdown-math.mjs"
    payload = (
        b"// Generated by paper-fetch scripts/sync_mathjax_engine.py; edit the source there.\n"
        + SOURCE.read_bytes()
    )
    digest_path = destination.with_suffix(".sha256")
    digest = hashlib.sha256(payload).hexdigest() + "\n"
    if args.check:
        if (
            not destination.exists()
            or destination.read_bytes() != payload
            or not digest_path.exists()
            or digest_path.read_text() != digest
        ):
            raise SystemExit(
                "LitRoot MathJax engine differs; run sync_mathjax_engine.py READER_ROOT"
            )
    else:
        destination.write_bytes(payload)
        digest_path.write_text(digest)


if __name__ == "__main__":
    main()
