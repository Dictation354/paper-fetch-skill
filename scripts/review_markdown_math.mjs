#!/usr/bin/env node
// Offline review only: reuse the explicitly selected reader installation.
import { access, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { parseArgs } from 'node:util'
import { createHash } from 'node:crypto'

const { values, positionals } = parseArgs({
  options: { 'modules-root': { type: 'string' }, output: { type: 'string' }, 'include-formulas': { type: 'boolean', default: false } },
  allowPositionals: true,
})
if (!values['modules-root'] || !positionals.length) {
  throw new Error('Usage: review_markdown_math.mjs --modules-root READER_DIR [--output REPORT.json] FILE.md ...')
}
const require = createRequire(resolve(values['modules-root'], 'package.json'))
const canonicalEngine = await readFile(new URL('../src/paper_fetch/resources/formula/mathjax_engine.mjs', import.meta.url), 'utf8')
const readerEngine = await readFile(resolve(values['modules-root'], 'src/shared/markdown-math.mjs'), 'utf8')
if (readerEngine !== '// Generated by paper-fetch scripts/sync_mathjax_engine.py; edit the source there.\n' + canonicalEngine) {
  throw new Error('Reader MathJax engine differs: run scripts/sync_mathjax_engine.py READER_DIR')
}
const paths = [dirname(require.resolve('react-markdown'))]
async function dependency(name) {
  return (await import(pathToFileURL(require.resolve(name, { paths })).href)).default
}
const { unified } = await import(pathToFileURL(require.resolve('unified', { paths })).href)
const [parse, gfm, math] = await Promise.all([
  dependency('remark-parse'), dependency('remark-gfm'), dependency('remark-math'),
])
const { createMathRenderer, mathjaxVersion, mathjaxExtensions } = await import(
  pathToFileURL(resolve(values['modules-root'], 'src/shared/markdown-math.mjs')).href
)
const parser = unified().use(parse).use(gfm).use(math)
const files = []
for (const path of positionals) {
  const markdown = await readFile(path, 'utf8')
  const tree = parser.parse(markdown)
  const renderer = createMathRenderer()
  const record = {
    path, sha256: createHash('sha256').update(markdown).digest('hex'),
    formulas: 0, inline: 0, display: 0, errors: [], warnings: [], assets: [], delimiterCandidates: [],
  }
  if (values['include-formulas']) record.formulaNodes = []
  function visit(node, ancestors = []) {
    if (node.type === 'text' && node.value.includes('$')) {
      record.delimiterCandidates.push({
        line: node.position.start.line, column: node.position.start.column,
        text: node.value,
      })
    }
    if ((node.type === 'image' || node.type === 'link') && node.url &&
        !/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(node.url)) {
      record.assets.push({ line: node.position.start.line, url: node.url })
    }
    if (node.type === 'math' || node.type === 'inlineMath') {
      // MarkdownReader's remarkStandaloneMath promotes a sole inline formula.
      const parent = ancestors.at(-1)
      const displayMode = node.type === 'math' || (parent?.type === 'paragraph' && parent.children.length === 1)
      record.formulas++
      record[displayMode ? 'display' : 'inline']++
      const location = {
        line: node.position.start.line, column: node.position.start.column,
        endLine: node.position.end.line, expression: node.value, displayMode,
        context: ancestors.map(n => n.type),
      }
      const { error } = renderer.render(node.value, displayMode)
      if (values['include-formulas']) record.formulaNodes.push(location)
      if (error) record.errors.push({ ...location, message: error.message })
    }
    for (const child of node.children ?? []) visit(child, [...ancestors, node])
  }
  visit(tree)
  for (const asset of record.assets) {
    try {
      await access(resolve(dirname(path), decodeURIComponent(asset.url.split(/[?#]/)[0])))
      asset.exists = true
    } catch {
      asset.exists = false
    }
  }
  files.push(record)
}
const report = {
  mathjax: mathjaxVersion,
  extensions: mathjaxExtensions,
  rules: ['remark-parse', 'remark-gfm', 'remark-math (singleDollarTextMath default)', 'MarkdownReader.remarkStandaloneMath'],
  files,
  totals: {
    files: files.length, formulas: files.reduce((n, f) => n + f.formulas, 0),
    errors: files.reduce((n, f) => n + f.errors.length, 0),
    warnings: files.reduce((n, f) => n + f.warnings.length, 0),
  },
}
const output = JSON.stringify(report, null, 2) + '\n'
if (values.output) await writeFile(values.output, output)
else process.stdout.write(output)
// A report with errors must never be mistaken for a clean verification.
if (report.totals.errors) process.exitCode = 1
